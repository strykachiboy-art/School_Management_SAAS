def test_update_notification_preferences(admin_client, school):
    payload = {
        "preferences": {
            "RESULT": {"email": True, "sms": False, "push": True, "in_app": True},
            "ATTENDANCE": {"email": True, "sms": True},
        }
    }

    response = admin_client.patch(f"/settings/{school.id}/notifications", json=payload)
    assert response.status_code == 200

    data = _json(response)
    assert data["notification_preferences"] == payload["preferences"]


def test_update_notification_preferences_merges_types(admin_client, school, school_settings):
    with admin_client.c.application.app_context():
        settings = _db.session.get(SchoolSettings, school_settings.id)
        settings.notification_preferences = {
            "RESULT": {"email": True},
            "ATTENDANCE": {"sms": True},
        }
        _db.session.commit()

    response = admin_client.patch(f"/settings/{school.id}/notifications", json={"preferences": {"FEES": {"email": True}}})
    assert response.status_code == 200

    data = _json(response)
    assert data["notification_preferences"] == {
        "RESULT": {"email": True},
        "ATTENDANCE": {"sms": True},
        "FEES": {"email": True},
    }


def test_update_notification_preferences_merges_channels(admin_client, school, school_settings):
    with admin_client.c.application.app_context():
        settings = _db.session.get(SchoolSettings, school_settings.id)
        settings.notification_preferences = {
            "RESULT": {"email": True, "sms": True, "push": True}
        }
        _db.session.commit()

    response = admin_client.patch(f"/settings/{school.id}/notifications", json={"preferences": {"RESULT": {"email": False}}})
    assert response.status_code == 200

    data = _json(response)
    assert data["notification_preferences"]["RESULT"] == {
        "email": False,
        "sms": True,
        "push": True,
    }


def test_update_notification_preferences_requires_preferences(admin_client, school):
    response = admin_client.patch(f"/settings/{school.id}/notifications", json={})
    assert response.status_code == 400


def test_update_notification_preferences_rejects_non_boolean_values(admin_client, school):
    response = admin_client.patch(f"/settings/{school.id}/notifications", json={"preferences": {"RESULT": {"email": "yes"}}})
    assert response.status_code in (200, 400)


