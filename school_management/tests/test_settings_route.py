def test_settings_are_persisted_after_route_update(admin_client, school):
    response = admin_client.patch(f"/settings/{school.id}/branding", json={
        "motto": "Persistent Motto",
        "phone": "08000000000",
    })
    assert response.status_code == 200

    with admin_client.c.application.app_context():
        settings = SchoolSettings.query.filter_by(school_id=school.id).first()
        assert settings is not None
        assert settings.motto == "Persistent Motto"
        assert settings.phone == "08000000000"


