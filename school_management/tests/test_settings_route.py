# ======================================================================
# HELPERS
# ======================================================================

def _json(response):
    assert response.is_json, response.get_data(as_text=True)
    return response.get_json()


# ======================================================================
# GET SETTINGS
# ======================================================================

def test_get_settings_returns_default_settings(admin_client, school):
    response = admin_client.get(f"/settings/{school.id}")
    assert response.status_code == 200

    data = _json(response)
    assert data["school_id"] == school.id
    assert data["logo_url"] is None
    assert data["emblem_url"] is None
    assert data["motto"] is None

    assert data["show_logo_on_report"] is True
    assert data["show_student_photo_on_report"] is True
    assert data["show_grade_on_report"] is True
    assert data["show_attendance_on_report"] is True
    assert data["show_teacher_remarks_on_report"] is True
    assert data["show_principal_remarks_on_report"] is False
    assert data["show_ranking_on_report"] is False
    assert data["enable_class_ranking"] is False

    assert data["require_result_pin"] is False
    assert data["result_pin_length"] == 4
    assert data["public_result_verification_enabled"] is True
    assert data["notification_preferences"] == {}


