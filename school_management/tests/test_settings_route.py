def test_reset_notification_preferences(admin_client, school):
    update_response = admin_client.patch(f"/settings/{school.id}/notifications", json={
        "preferences": {
            "RESULT": {"email": True, "sms": True},
            "ATTENDANCE": {"in_app": True},
        }
    })
    assert update_response.status_code == 200

    response = admin_client.post(f"/settings/{school.id}/notifications/reset")
    assert response.status_code == 200

    data = _json(response)
    assert data["notification_preferences"] == {}


def test_reset_notification_preferences_is_idempotent(admin_client, school):
    response = admin_client.post(f"/settings/{school.id}/notifications/reset")
    assert response.status_code == 200
    assert _json(response)["notification_preferences"] == {}

    response = admin_client.post(f"/settings/{school.id}/notifications/reset")
    assert response.status_code == 200
    assert _json(response)["notification_preferences"] == {}


